    /** 按品牌 + 关键字过滤（关键字匹配车型/OE/类型） */
    fun search(keyword: String, brand: String?): List<Entry> {
        val kw = keyword.trim().lowercase()
        return ALL.filter { entry ->
            (brand == null || entry.brand == brand) &&
                    (kw.isEmpty() ||
                            entry.model.lowercase().contains(kw) ||
                            entry.oe.lowercase().contains(kw) ||
                            entry.type.contains(kw) ||
                            entry.brand.lowercase().contains(kw))
        }
    }
